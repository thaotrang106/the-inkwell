/**
 * Trả về danh sách sách cá nhân hóa dựa trên thể loại đang chọn
 * và thông tin độc giả đang đăng nhập.
 */
export function getPersonalizedBooksForGenre(
  genreSlug: string | undefined,
  currentReader: DemoReader | null | undefined,
  fetchedBooks?: any[]
): DemoBook[] {
  // 1. Nếu không chọn thể loại nào (Tất cả Thịnh hành) -> Dùng danh sách cá nhân hóa mặc định của độc giả đăng nhập
  if (!genreSlug || genreSlug === "all") {
    if (currentReader && currentReader.books && currentReader.books.length > 0) {
      return currentReader.books;
    }
    return currentReader ? (DEMO_READERS.find(r => r.user_id === currentReader.user_id)?.books || []) : [];
  }

  const cleanSlug = genreSlug.toLowerCase().trim();

  // 2. Nếu có danh mục tuyển chọn chuẩn trong GENRE_PERSONALIZED_MAP
  const curatedGenreList = GENRE_PERSONALIZED_MAP[cleanSlug];
  if (curatedGenreList && curatedGenreList.length > 0) {
    return curatedGenreList;
  }

  // 3. Nếu thể loại có sách trả về từ API backend /api/books/by-genre
  if (fetchedBooks && fetchedBooks.length > 0) {
    const EXPLANATIONS = [
      "Khuyên Đọc Cho Bạn",
      "Tương Đồng Phong Cách",
      "Cốt Truyện Kịch Tính",
      "Đánh Giá Cao Nhất",
      "Kiệt Tác Thể Loại",
    ];

    const meta = GENRE_METADATA_MAP[cleanSlug];
    const genreTitle = meta ? meta.title : cleanSlug;

    return fetchedBooks.slice(0, 5).map((book, idx) => ({
      book_id: Number(book.book_id),
      title: book.title || "Tác phẩm tuyển chọn",
      author: book.author || book.authors || "Tác giả văn học",
      image_url: book.image_url || "",
      rating: Number(book.score || book.rating || 4.2),
      price: Number(book.price || 180000),
      original_price: Number(book.original_price || 220000),
      hybrid_score: Math.max(88, 98 - idx * 2),
      explanation: book.explanation || EXPLANATIONS[idx % EXPLANATIONS.length],
      because: book.because || `Gu đọc thể loại ${genreTitle}`,
    }));
  }

  // 4. Fallback an toàn: nếu độc giả đã đăng nhập, ưu tiên gu sở trường
  if (currentReader) {
    if (cleanSlug === "fantasy") return DEMO_READERS[0].books;
    if (cleanSlug === "philosophy" || cleanSlug === "classics") return DEMO_READERS[1].books;
    if (cleanSlug === "mystery" || cleanSlug === "thriller") return DEMO_READERS[2].books;
    return currentReader.books;
  }

  return [];
}
